use p4kx_audio::{ContainerKind, HircKind, MediaStorage, SoundSource};

use super::{AtlTrigger, BrokenLink, IndexedSoundbank, WwiseEvent};

/// The kind of a `HIRC` object on the way from a Wwise event to a sound.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum NodeKind {
    /// The Event object the way starts at.
    Event,
    /// An Action object.
    Action,
    /// A random container.
    Random,
    /// A sequence container.
    Sequence,
    /// A switch container.
    Switch,
    /// A blend container.
    Blend,
    /// A Sound object.
    Sound,
    /// Any other object, whose layout this reader does not follow.
    Other(HircKind),
}

impl NodeKind {
    /// Returns the kind of a container.
    #[must_use]
    pub const fn of_container(kind: ContainerKind) -> Self {
        match kind {
            ContainerKind::Random => Self::Random,
            ContainerKind::Sequence => Self::Sequence,
            ContainerKind::Switch => Self::Switch,
            ContainerKind::Blend => Self::Blend,
            _ => Self::Other(HircKind::Other(0)),
        }
    }

    /// Returns a stable name for the kind, e.g. `random` or `music_track`, for scripts.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Event => "event",
            Self::Action => "action",
            Self::Random => "random",
            Self::Sequence => "sequence",
            Self::Switch => "switch",
            Self::Blend => "blend",
            Self::Sound => "sound",
            Self::Other(kind) => other_name(kind),
        }
    }
}

const fn other_name(kind: HircKind) -> &'static str {
    match kind {
        HircKind::State => "state",
        HircKind::Sound => "sound",
        HircKind::Action => "action",
        HircKind::Event => "event",
        HircKind::RandomSequenceContainer => "random_sequence",
        HircKind::SwitchContainer => "switch",
        HircKind::ActorMixer => "actor_mixer",
        HircKind::AudioBus => "audio_bus",
        HircKind::LayerContainer => "blend",
        HircKind::MusicSegment => "music_segment",
        HircKind::MusicTrack => "music_track",
        HircKind::MusicSwitch => "music_switch",
        HircKind::MusicPlaylist => "music_playlist",
        HircKind::Attenuation => "attenuation",
        HircKind::DialogueEvent => "dialogue_event",
        HircKind::FxShareSet => "fx_share_set",
        HircKind::FxCustom => "fx_custom",
        HircKind::AuxiliaryBus => "auxiliary_bus",
        HircKind::Lfo => "lfo",
        HircKind::Envelope => "envelope",
        HircKind::AudioDevice => "audio_device",
        HircKind::TimeModulator => "time_modulator",
        HircKind::Other(_) => "unknown",
    }
}

/// One step of a container path: an object and its kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct PathStep {
    /// The kind of the object.
    pub kind: NodeKind,
    /// The object ID.
    pub id: u32,
}

/// Where the media of a sound variant comes from, as its Sound object states it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum SourceKind {
    /// Held in memory: embedded in a soundbank or loaded as a loose WEM.
    Embedded,
    /// Its start embedded in a soundbank, the rest streamed from a loose WEM.
    PrefetchStreamed,
    /// Streamed from a loose WEM.
    Streamed,
    /// Generated by a source plug-in; no WEM holds it.
    Plugin,
    /// A storage value this reader does not know.
    Other(u8),
}

impl SourceKind {
    /// Returns the kind of a Sound object's source.
    #[must_use]
    pub const fn of(source: &SoundSource) -> Self {
        if source.is_source_plugin() {
            return Self::Plugin;
        }
        match source.storage {
            MediaStorage::Embedded => Self::Embedded,
            MediaStorage::PrefetchStreamed => Self::PrefetchStreamed,
            MediaStorage::Streamed => Self::Streamed,
            MediaStorage::Other(storage) => Self::Other(storage),
        }
    }

    /// Returns a stable name for the kind, e.g. `embedded`, for scripts.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Embedded => "embedded",
            Self::PrefetchStreamed => "prefetch_streamed",
            Self::Streamed => "streamed",
            Self::Plugin => "plugin",
            Self::Other(_) => "other",
        }
    }
}

/// Where the bytes of a WEM are.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum WemLocation<'i> {
    /// Embedded in a soundbank's `DATA` section; for a prefetched WEM only its start.
    Soundbank {
        /// The soundbank.
        soundbank: &'i IndexedSoundbank,
        /// The offset of the WEM in the `DATA` section.
        offset: u64,
        /// The length of the WEM in the soundbank.
        len: u64,
    },
    /// A loose WEM Entry of the Archive: the media of a streamed sound.
    Entry {
        /// The path of the Entry.
        path: &'i str,
        /// The position of the Entry in `Archive::entries`.
        entry: u32,
        /// The language folder the Entry lies in, or `None` when it is not localised.
        language: Option<&'i str>,
        /// The uncompressed length of the Entry.
        len: u64,
    },
}

impl<'i> WemLocation<'i> {
    /// Returns the language folder the WEM lies in, or `None` when it is not localised.
    #[must_use]
    pub fn language(&self) -> Option<&'i str> {
        match *self {
            Self::Soundbank { soundbank, .. } => soundbank.language(),
            Self::Entry { language, .. } => language,
        }
    }
}

/// One sound a trigger may play: a Sound object reached from a Wwise event through actions and
/// containers, with its WEM.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SoundVariant<'i> {
    pub(crate) event: &'i WwiseEvent,
    pub(crate) soundbank: &'i IndexedSoundbank,
    pub(crate) sound_id: u32,
    pub(crate) path: Box<[PathStep]>,
    pub(crate) source: SoundSource,
    pub(crate) location: Option<WemLocation<'i>>,
    pub(crate) localised: bool,
    pub(crate) language: Option<&'i str>,
    pub(crate) fallback: bool,
}

impl<'i> SoundVariant<'i> {
    /// Returns whether the sound is localised: its source is language-specific or its soundbank
    /// lies in a language folder.
    #[must_use]
    pub const fn is_localised(&self) -> bool {
        self.localised
    }

    /// Returns the language the sound was resolved in, or `None` when it is not localised or its
    /// WEM was not found.
    #[must_use]
    pub const fn language(&self) -> Option<&'i str> {
        self.language
    }

    /// Returns whether the language is the fallback language, not the one asked for.
    #[must_use]
    pub const fn used_fallback(&self) -> bool {
        self.fallback
    }

    /// Returns the Wwise event the variant is reached from.
    #[must_use]
    pub const fn event(&self) -> &'i WwiseEvent {
        self.event
    }

    /// Returns the soundbank whose `HIRC` section leads from the event to the sound.
    #[must_use]
    pub const fn soundbank(&self) -> &'i IndexedSoundbank {
        self.soundbank
    }

    /// Returns the container path from the Event object to the Sound object, both included.
    #[must_use]
    pub fn path(&self) -> &[PathStep] {
        &self.path
    }

    /// Returns the ID of the Sound object.
    #[must_use]
    pub const fn sound_id(&self) -> u32 {
        self.sound_id
    }

    /// Returns the WEM ID of the sound's media, or `None` for a source plug-in, which has no WEM.
    #[must_use]
    pub const fn wem_id(&self) -> Option<u32> {
        if self.source.is_source_plugin() {
            None
        } else {
            Some(self.source.source_id)
        }
    }

    /// Returns the media source as the Sound object states it.
    #[must_use]
    pub const fn source(&self) -> &SoundSource {
        &self.source
    }

    /// Returns where the media comes from.
    #[must_use]
    pub const fn source_kind(&self) -> SourceKind {
        SourceKind::of(&self.source)
    }

    /// Returns where the WEM's bytes are, or `None` when no soundbank embeds it.
    #[must_use]
    pub const fn location(&self) -> Option<&WemLocation<'i>> {
        self.location.as_ref()
    }
}

/// The sounds of an audio trigger: every variant its Wwise events lead to, and every place where
/// the way from an event to a WEM breaks.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TriggerSounds<'i> {
    pub(crate) trigger: &'i AtlTrigger,
    pub(crate) definition_path: Option<&'i str>,
    pub(crate) variants: Vec<SoundVariant<'i>>,
    pub(crate) breaks: Vec<BrokenLink<'i>>,
}

impl<'i> TriggerSounds<'i> {
    /// Returns the trigger's ATL definition.
    #[must_use]
    pub const fn trigger(&self) -> &'i AtlTrigger {
        self.trigger
    }

    /// Returns the path of the ATL definition Entry.
    #[must_use]
    pub const fn definition_path(&self) -> Option<&'i str> {
        self.definition_path
    }

    /// Returns the variants in the order of the trigger's events, their soundbanks in path order
    /// and the containers' children in bank order.
    #[must_use]
    pub fn variants(&self) -> &[SoundVariant<'i>] {
        &self.variants
    }

    /// Returns the broken links in the same order.
    #[must_use]
    pub fn breaks(&self) -> &[BrokenLink<'i>] {
        &self.breaks
    }
}
