#[expect(
    clippy::indexing_slicing,
    reason = "compile-time evaluation within the fixed table sizes, where a slip fails the build"
)]
const fn spread(masks: &[u16; 64]) -> [u32; 64] {
    let mut out = [0; 64];
    let mut partition = 0;
    while partition < 64 {
        let mut texel = 0;
        while texel < 16 {
            out[partition] |= ((masks[partition] as u32 >> texel) & 1) << (2 * texel);
            texel += 1;
        }
        partition += 1;
    }
    out
}

#[expect(
    clippy::indexing_slicing,
    reason = "compile-time evaluation within the fixed table sizes, where a slip fails the build"
)]
const fn pack(subsets: &[[u8; 16]; 64]) -> [u32; 64] {
    let mut out = [0; 64];
    let mut partition = 0;
    while partition < 64 {
        let mut texel = 0;
        while texel < 16 {
            out[partition] |= (subsets[partition][texel] as u32) << (2 * texel);
            texel += 1;
        }
        partition += 1;
    }
    out
}

#[expect(
    clippy::indexing_slicing,
    reason = "compile-time evaluation within the fixed table sizes, where a slip fails the build"
)]
const fn anchors(second: &[u8; 64], third: &[u8; 64]) -> [u16; 64] {
    let mut out = [0; 64];
    let mut partition = 0;
    while partition < 64 {
        out[partition] = 1 | (1 << second[partition]) | (1 << third[partition]);
        partition += 1;
    }
    out
}
