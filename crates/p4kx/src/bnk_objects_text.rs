use std::fmt::{self, Display};
use std::io::{self, Write};

use p4kx_extraction::text_line::one_line;

use crate::bnk_objects_json::{
    ClipJson, Detail, ItemJson, ObjectJson, SegmentDetail, SoundDetail, TrackDetail,
};

const INDENT: &str = "    ";
const DEFAULT_STATUS: &str = "decoded";
const NO_PARENT: &str = "-";

/// Writes an object as a line of its own followed by indented lines for its error and details.
pub(crate) fn write_object(out: &mut impl Write, object: &ObjectJson<'_>) -> io::Result<()> {
    let parent = object
        .parent
        .map_or_else(|| NO_PARENT.to_owned(), |parent| parent.to_string());
    write!(
        out,
        "#{}  {}  {}  parent {parent}  children {}",
        object.index,
        object.kind,
        object.id,
        object.children.len()
    )?;
    if !object.children.is_empty() {
        write!(out, " [{}]", Ids(&object.children))?;
    }
    if object.status != DEFAULT_STATUS {
        write!(out, "  {}", object.status)?;
    }
    writeln!(out)?;
    if let Some(error) = &object.error {
        writeln!(out, "{INDENT}{}", one_line(error))?;
    }
    match &object.detail {
        Some(Detail::Sound(sound)) => sound_lines(out, sound),
        Some(Detail::Action(action)) => {
            write!(
                out,
                "{INDENT}action {:#06x} target {}",
                action.action_type, action.target
            )?;
            if let Some(bank) = action.soundbank_id {
                write!(out, " soundbank {bank}")?;
            }
            writeln!(out)
        }
        Some(Detail::Container(container)) => {
            writeln!(out, "{INDENT}kind {}", container.container_kind)
        }
        Some(Detail::Segment(segment)) => segment_lines(out, segment),
        Some(Detail::Track(track)) => track_lines(out, track),
        Some(Detail::Switch(switch)) => {
            writeln!(
                out,
                "{INDENT}{} transition rules, groups [{}], targets [{}]",
                switch.rule_count,
                Ids(switch.group_ids),
                Ids(switch.targets)
            )
        }
        Some(Detail::Playlist(playlist)) => {
            writeln!(out, "{INDENT}{} transition rules", playlist.rule_count)?;
            playlist
                .items
                .iter()
                .try_for_each(|item| item_line(out, item))
        }
        None => Ok(()),
    }
}

fn sound_lines(out: &mut impl Write, sound: &SoundDetail) -> io::Result<()> {
    write!(
        out,
        "{INDENT}source {} {}, plugin {:#x}, {} bytes in memory",
        sound.source_id, sound.storage, sound.plugin_id, sound.in_memory_size
    )?;
    if sound.language_specific {
        write!(out, ", language-specific")?;
    }
    if sound.source_plugin {
        write!(out, ", generated by a plug-in")?;
    }
    writeln!(out)
}

fn segment_lines(out: &mut impl Write, segment: &SegmentDetail<'_>) -> io::Result<()> {
    writeln!(
        out,
        "{INDENT}duration {:.3} ms, {} bpm, {}/{}",
        segment.duration_ms, segment.tempo, segment.beats_per_bar, segment.beat_value
    )?;
    for marker in &segment.markers {
        writeln!(
            out,
            "{INDENT}marker {} at {:.3} ms \"{}\"",
            marker.id,
            marker.position_ms,
            one_line(marker.name)
        )?;
    }
    for stinger in &segment.stingers {
        writeln!(
            out,
            "{INDENT}stinger trigger {} plays segment {}",
            stinger.trigger_id, stinger.segment_id
        )?;
    }
    Ok(())
}

fn track_lines(out: &mut impl Write, track: &TrackDetail<'_>) -> io::Result<()> {
    writeln!(out, "{INDENT}{} track", track.track_kind)?;
    if let Some(switch) = &track.switch {
        let group = if switch.group_type == 0 {
            "switch"
        } else {
            "state"
        };
        writeln!(
            out,
            "{INDENT}follows {group} group {}, default {}, switches [{}]",
            switch.group_id,
            switch.default_switch,
            Ids(switch.switches)
        )?;
    }
    track.clips.iter().try_for_each(|clip| clip_line(out, clip))
}

fn clip_line(out: &mut impl Write, clip: &ClipJson) -> io::Result<()> {
    write!(
        out,
        "{INDENT}clip source {} at {:.3} ms, trim {:.3}..{:.3} ms of {:.3} ms",
        clip.source_id,
        clip.play_at_ms,
        clip.begin_trim_ms,
        clip.end_trim_ms,
        clip.source_duration_ms
    )?;
    if clip.event_id != 0 {
        write!(out, ", posts event {}", clip.event_id)?;
    }
    writeln!(out)
}

fn item_line(out: &mut impl Write, item: &ItemJson) -> io::Result<()> {
    let nested = INDENT.repeat(item.depth.saturating_add(1));
    write!(out, "{INDENT}{nested}item {} ", item.item_id)?;
    if item.segment_id == 0 {
        write!(out, "group of {}", item.children)?;
    } else {
        write!(out, "segment {}", item.segment_id)?;
    }
    write!(out, ", {}, {}", play_mode(item.play_mode), loops(item))?;
    if item.uses_weight {
        write!(out, ", weight {}", item.weight)?;
    }
    if item.avoid_repeat_count > 0 {
        write!(out, ", avoids {} repeats", item.avoid_repeat_count)?;
    }
    if item.shuffle {
        write!(out, ", shuffled")?;
    }
    writeln!(out)
}

fn play_mode(mode: u32) -> String {
    match mode {
        0 => "random".to_owned(),
        1 => "sequence continuous".to_owned(),
        2 => "random step".to_owned(),
        3 => "sequence step".to_owned(),
        other => format!("play mode {other}"),
    }
}

fn loops(item: &ItemJson) -> String {
    let count = match item.loops {
        0 => "loops endless".to_owned(),
        count => format!("loops {count}"),
    };
    if item.loop_min == 0 && item.loop_max == 0 {
        count
    } else {
        format!("{count} (range {}..{})", item.loop_min, item.loop_max)
    }
}

/// Space-separated IDs.
struct Ids<'a>(&'a [u32]);

impl Display for Ids<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (position, id) in self.0.iter().enumerate() {
            if position > 0 {
                f.write_str(" ")?;
            }
            write!(f, "{id}")?;
        }
        Ok(())
    }
}
